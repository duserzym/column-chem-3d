const ul = (x) => x / 1000;

/** Column geometry (mm, mL). heatshrink = FEP/PTFE heat-shrink micro-column. */
function geom(kind, bed_mL, id_mm, reservoir_mL, extra = {}) {
  const r = id_mm / 20; // cm
  const bedHeight_mm = (bed_mL / (Math.PI * r * r)) * 10;
  return { kind, bed_mL, id_mm, bedHeight_mm, reservoir_mL, ...extra };
}

