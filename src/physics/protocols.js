const HCl = (M) => ({ acid: 'HCl', M });
const HBr = (M) => ({ acid: 'HBr', M });
const HNO3 = (M) => ({ acid: 'HNO3', M });
const H2O = { acid: 'H2O', M: 0 };
const HClHF = (M, HF) => ({ acid: 'HCl-HF', M, HF });
const HCIT = (label) => ({ acid: 'HCit', M: 0.45, label });
